// The construction office tick has two versions, chosen by the byte [game+0x14455] (dispatcher
// 0x13E139): 0x146B10 when it is set, 0x145900 otherwise. Both take a concrete plant (source
// kind 3) or an asphalt plant (kind 4) as able to produce only when the plant holds its inputs
// AND its people list (+0xBC0..+0xBC8) is not empty; otherwise the office shows "The
// concrete/asphalt plant can't produce ..." (strings 1623/1625) or never sends its mixers and
// dumpers there. Each patch keeps the input checks and drops the people test.
//
// - 0x145900 and the office window go through 0x1561C0, which walks the office sources
//   (+0xF78..+0xF80) and keeps the plant with `cmovne` on the people count: `cmovne` -> `mov`.
// - 0x146B10 picks sources through 0x155960, which calls 0x151780 for a concrete plant and
//   0x151910 for an asphalt plant (a customs house, type 0x14, is taken directly). Both return
//   false when the plant needs staff ($WORKERS_NEEDED + $PROFESORS_NEEDED > 0) and nobody is
